const STORE_KEY = 'ach.lang';

function detect() {
  try {
    const saved = globalThis.localStorage && globalThis.localStorage.getItem(STORE_KEY);
    if (saved === 'en' || saved === 'zh') return saved;
  } catch (_) { /* storage blocked */ }
  const nav = (globalThis.navigator && (globalThis.navigator.language || '')) || '';
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let lang = detect();

export function getLang() { return lang; }

/** the account's or the hub's language, unless the person picked one on this device (not saved). */
export function adoptLang(next, force) {
  if (next !== 'en' && next !== 'zh') return false;
  let saved = null;
  try { saved = globalThis.localStorage && globalThis.localStorage.getItem(STORE_KEY); } catch (_) { /* blocked */ }
  if (!force && (saved === 'en' || saved === 'zh')) return false;
  if (lang === next) return false;
  lang = next;
  if (force) { try { globalThis.localStorage && globalThis.localStorage.setItem(STORE_KEY, lang); } catch (_) { /* ignore */ } }
  return true;
}

export function setLang(next) {
  lang = next === 'zh' ? 'zh' : 'en';
  try { globalThis.localStorage && globalThis.localStorage.setItem(STORE_KEY, lang); } catch (_) { /* ignore */ }
}

/** True when the key exists (in the current language or English). */
export function has(key) { return !!((DICT[lang] && key in DICT[lang]) || key in DICT.en); }

/** Count-aware t(): "{key}_one" for n === 1 when the current language has it (English plurals). */
export function tn(key, n, vars) {
  const one = `${key}_one`;
  const k = Number(n) === 1 && DICT[lang] && one in DICT[lang] ? one : key;
  return t(k, { n, ...(vars || {}) });
}

export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
